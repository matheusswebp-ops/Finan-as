import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hero?: boolean; interactive?: boolean }
>(({ className, hero, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "card-shell p-6",
      hero && "card-hero",
      interactive &&
        "transition-all duration-300 hover:border-primary/40 hover:shadow-[0_0_0_1px_hsl(var(--primary)/0.15),0_24px_60px_-30px_hsl(var(--primary)/0.4)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

